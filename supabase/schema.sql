create table if not exists public.admin_users (
  user_id uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.analytics_events (
  id bigint generated by default as identity primary key,
  event_name text not null check (event_name in ('page_view', 'click')),
  path text not null default '/',
  session_id text not null check (char_length(session_id) between 16 and 128),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists analytics_events_created_at_idx
  on public.analytics_events (created_at desc);
create index if not exists analytics_events_session_id_idx
  on public.analytics_events (session_id);

alter table public.admin_users enable row level security;
alter table public.analytics_events enable row level security;

create or replace function public.is_admin()
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1 from public.admin_users
    where user_id = (select auth.uid())
  );
$$;

revoke all on public.admin_users from anon, authenticated;
revoke all on public.analytics_events from anon, authenticated;
grant insert on public.analytics_events to anon, authenticated;
grant select on public.analytics_events to authenticated;

drop policy if exists "public can record analytics" on public.analytics_events;
create policy "public can record analytics"
on public.analytics_events for insert
to anon, authenticated
with check (true);

drop policy if exists "admins can read analytics" on public.analytics_events;
create policy "admins can read analytics"
on public.analytics_events for select
to authenticated
using ((select public.is_admin()));

